import frappe
from frappe import _
from frappe.model.document import Document

from itemflow.extensions import get_extra_filter_fields

FILTER_FIELDS = (
	"show_filter_brand",
	"show_filter_stock_uom",
)
MAX_FILTER_FIELDS = 10


class ItemflowSettings(Document):
	def validate(self):
		if self.low_stock_threshold < 0:
			frappe.throw(_("Low stock threshold cannot be negative"))
		if self.default_qty < 1:
			frappe.throw(_("Default quantity must be at least 1"))
		if self.max_items < 1:
			frappe.throw(_("Maximum items per operation must be at least 1"))
		if self.max_items > 30:
			frappe.throw(_("Maximum items per operation cannot exceed 30"))
		if self.add_chunk_size < 1:
			frappe.throw(_("Items per batch must be at least 1"))
		if self.add_chunk_size > self.max_items:
			frappe.throw(_("Items per batch cannot exceed the maximum items per operation"))

		self._validate_max_filter_fields()
		self._validate_filter_rows()

	def _validate_filter_rows(self):
		allowed = {definition["fieldname"] for definition in get_extra_filter_fields()}
		for row in self.get("filters") or []:
			if row.fieldname and row.fieldname not in allowed:
				frappe.throw(
					_("Filter field {0} is not registered by an installed extension").format(row.fieldname)
				)

	def _validate_max_filter_fields(self):
		enabled_count = sum(1 for field in FILTER_FIELDS if self.get(field))
		enabled_count += sum(1 for row in (self.get("filters") or []) if row.visible)
		if enabled_count > MAX_FILTER_FIELDS:
			frappe.throw(
				_("A maximum of {0} filter fields can be active. You currently have {1} active.").format(
					MAX_FILTER_FIELDS, enabled_count
				)
			)

	def on_update(self):
		# Clear the settings cache (used by get_cached_doc and extend_bootinfo)
		frappe.cache().delete_key("item_selector_settings")

		# Clear the item selector caches (keys generated by @redis_cache).
		# The names must match the decorated functions (_cached_*).
		frappe.cache().delete_keys("itemflow.api._cached_descendant_groups")
		frappe.cache().delete_keys("itemflow.api._cached_item_groups_hierarchy")
